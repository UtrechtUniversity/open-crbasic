"""Generate vscode/syntaxes/crbasic.tmLanguage.json from the CR6 instruction catalog.

    python tools/gen_grammar.py            write the grammar
    python tools/gen_grammar.py --check    exit 1 if the committed file differs from a fresh one

Names come from `opencrbasic.catalog` (the CR6 profile's tables), operators from the lexer's
operator list. Every regex is case-insensitive (`(?i)` first) and sticks to syntax common to
Oniguruma (VS Code) and Python `re`. See docs/lsp-api.md, "Instruction catalog".
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from opencrbasic import lexer  # noqa: E402
from opencrbasic.catalog import InstructionCatalog  # noqa: E402

OUTPUT = ROOT / "vscode" / "syntaxes" / "crbasic.tmLanguage.json"
PROFILE = "cr6"

# Word operators: rows of the function table that the parser treats as operators
# (`checker/structure.py` `_BINARY_WORDS`, `parser.py` `NOT`/`TO`/`IS` handling).
OPERATOR_WORDS = ("AND", "EQV", "IMP", "IS", "MOD", "NOT", "OR", "TO", "XOR")
# Lexer punctuation that is not an operator for highlighting.
_PUNCTUATION = {"(", ")", ",", ".", ":", ";", "{", "}", "#", "!", "@"}
_META = set("\\^$.|?*+()[]{}-")

_BEFORE = r"(?<![A-Za-z0-9_$.])"
_AFTER = r"(?![A-Za-z0-9_$])"


def _esc(text: str) -> str:
    return "".join("\\" + c if c in _META else c for c in text)


_WORD_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\$?")


def _alternation(names) -> str:
    ordered = sorted(set(names), key=lambda n: (-len(n), n.upper(), n))
    return "(?:" + "|".join(_esc(n) for n in ordered) + ")"


def _words(names) -> str:
    return "(?i)" + _BEFORE + _alternation(names) + _AFTER


def build() -> dict:
    cat = InstructionCatalog.for_profile(PROFILE)
    taken: set[str] = set()

    def claim(names) -> list[str]:
        # `<<` and `>>` are catalog "functions" but operators: no word alternation takes them
        out = [n for n in names if n.upper() not in taken and _WORD_NAME.fullmatch(n)]
        taken.update(n.upper() for n in out)
        return out

    keywords = claim(cat.names("keyword"))
    operator_words = claim(n for n in cat.names("function") if n.upper() in OPERATOR_WORDS)
    instructions = claim(cat.names("instruction"))
    functions = claim(cat.names("function"))
    constants = claim(cat.names("symbol"))
    operators = sorted((op for op in lexer._OPERATORS if op not in _PUNCTUATION),
                       key=lambda o: (-len(o), o))

    repository = {
        "comment": {
            "name": "comment.line.apostrophe.crbasic",
            "match": "'.*$",
        },
        "string": {
            "name": "string.quoted.double.crbasic",
            "match": '"(?:[^"]|"")*(?:"|$)',
        },
        "number": {
            "patterns": [
                {"name": "constant.numeric.hex.crbasic",
                 "match": "(?i)&H[0-9A-F]+" + _AFTER},
                {"name": "constant.numeric.binary.crbasic",
                 "match": "(?i)&B[01]+" + _AFTER},
                {"name": "constant.numeric.decimal.crbasic",
                 "match": r"(?i)(?<![A-Za-z0-9_$])(?<![A-Za-z0-9_$]\.)"
                          r"(?:\d+\.\d*|\.\d+|\d+)(?:E[+-]?\d+)?(?:R(?![A-Za-z0-9_$]))?"},
            ],
        },
        "directive": {
            "match": r"(?i)^\s*(#\s*(?:If_no_remove|ElseIf|UnDef|EndIf|Else|If))(?![A-Za-z0-9_$])",
            "captures": {"1": {"name": "keyword.control.directive.crbasic"}},
        },
        "keyword": {
            "name": "keyword.control.crbasic",
            "match": _words(keywords),
        },
        "operator-word": {
            "name": "keyword.operator.word.crbasic",
            "match": _words(operator_words),
        },
        "instruction": {
            "name": "support.function.instruction.crbasic",
            "match": _words(instructions),
        },
        "builtin-function": {
            "name": "support.function.builtin.crbasic",
            "match": _words(functions),
        },
        "constant": {
            "name": "support.constant.crbasic",
            "match": _words(constants),
        },
        "operator": {
            "name": "keyword.operator.crbasic",
            "match": "|".join(_esc(op) for op in operators),
        },
    }
    order = ["comment", "string", "directive", "number", "keyword", "operator-word",
             "instruction", "builtin-function", "constant", "operator"]
    return {
        "information_for_contributors": [
            "Generated by opencrbasic/tools/gen_grammar.py from the CR6 instruction catalog.",
            "Do not edit by hand; run the generator (see docs/lsp-api.md, Instruction catalog).",
        ],
        "name": "CRBasic",
        "scopeName": "source.crbasic",
        "patterns": [{"include": "#" + key} for key in order],
        "repository": repository,
    }


def render() -> str:
    return json.dumps(build(), indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed grammar is stale")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else None
        if current != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run: python tools/gen_grammar.py",
                  file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
